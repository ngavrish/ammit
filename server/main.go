		if held {
			writeJSON(w, http.StatusConflict, map[string]any{
				"taken": false, "holder": holder, "since": at, "expires": expires})
			return
		}
		writeJSON(w, http.StatusOK, map[string]any{
			"taken": true, "holder": in.Holder, "since": at, "expires": now + in.TTL})
