// One open action per ticket.
//
// The keeper, the watchdog, a person through POST /queue and every stop of a
// run act on a ticket, and until this table they did so each on its own
// reading of the record. 2026-11-07, APF-3313 (watchdog_cycles 465-469):
// cycle 3's fix run WD-9519cad8-3 was working - it opened the right PR, #1194,
// nine minutes later - when the keeper resumed the ticket a minute into the
// fix. The resume hit the same red gate, the watchdog read it as cycle 3
// failing, loops.laps_watchdog was spent, and the fix was never merged. The
// keeper's busy check asks for runs and queue rows named APF-3313, and the fix
// run is named WD-9519cad8-3: nothing it could read said the ticket was taken.
//
// So taking a ticket is a row here, and the unique partial index below lets
// Postgres, not a reading of the record, say who has it: whoever inserts first
// owns the decision, and the other gets a unique violation and does nothing.
//
//	resume  a queue row that resumes the ticket (keeper, watchdog's fresh
//	        budget, a person). Open from the insert of the row until the row
//	        turns into a run that started, or is closed without one.
//	fix     a watchdog cycle, from its start to its end (done, dropped,
//	        failed, left). The cycle's own resume is queued under it
//	        (queue_id), not beside it.
//	stop    a stop ordered through act() - a person's /act or a judgement of
//	        ammit's - from the order until the run's row is finished. The run
//	        is "closing" meanwhile (GET /runs state). Past timeouts.run_close
//	        ammit closes the row itself, BLOCKED.
//
// Precedence, where the index alone would refuse:
//
//   - A stop always takes over. Refusing a stop leaves a run running, so an
//     open resume or fix is closed ("taken over by a stop") and the stop
//     opens; a resume row still waiting in the queue is withdrawn with it. A
//     fix's cycle goes on and takes its action back once the stop has closed
//     (holdCycle), and its own logic - a run stopped by hand ends the chain -
//     decides what follows.
//   - A person's resume (POST /queue with rerun=resume) is always queued. A
//     resume still waiting under another action is replaced by it (withdrawn,
//     its action closed); under a watchdog fix it becomes the cycle's resume,
//     so the cycle follows the person's run instead of queueing a second one.
//     Beside a stop, or beside a resume whose row is already starting, it is
//     queued without an action of its own and the log says so.
//   - The keeper and the watchdog never take over: they lose the insert and
//     leave the ticket to its holder.
//
// Nothing is held in memory: an action left open by a process that died is
// tied to a queue row, a cycle or a run, and sweepActions closes it on the
// tick once that thing says it is over, writing why.
//
// No LISTEN/NOTIFY: both sides already act on the same tick, so a wake-up
// would only move work from one loop to another. The index is the guarantee.
const actionsSchema = `
CREATE TABLE IF NOT EXISTS ticket_actions (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket   TEXT NOT NULL,
    kind     TEXT NOT NULL,              -- resume | fix | stop
    owner    TEXT NOT NULL,              -- keeper | watchdog | person | ammit
    run      TEXT,                       -- resume: the source run; fix: the dropped run; stop: the run stopped
    cycle_id bigint,                     -- fix: its watchdog_cycles row
    queue_id bigint,                     -- the queue row of the resume queued under it
    state    TEXT NOT NULL DEFAULT 'open', -- open | done | failed
    opened   double precision NOT NULL,
    closed   double precision,
    why      TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ticket_actions_one_open ON ticket_actions (ticket) WHERE state = 'open';
CREATE INDEX IF NOT EXISTS ticket_actions_ticket ON ticket_actions (ticket, opened DESC);`

const (
	actResume = "resume"
	actFix    = "fix"
	actStop   = "stop"
)

// actionOwner is the context key /act sets, so a stop it orders is a person's.
const actionOwner = "\x00owner"

type ticketAction struct {
	id                       int64
	ticket, kind, owner, run string
	cycle, queue             sql.NullInt64
	opened                   float64
}

func (a *ticketAction) String() string {
	s := fmt.Sprintf("%s by %s (action %d", a.kind, a.owner, a.id)
	if a.cycle.Valid {
		s += fmt.Sprintf(", cycle %d", a.cycle.Int64)
	}
	if a.queue.Valid {
		s += fmt.Sprintf(", queue %d", a.queue.Int64)
	}
	if a.run != "" {
		s += ", run " + shortRun(a.run)
	}
	return s + ")"
}

// querier is the pool or a transaction on it.
type querier interface {
	Exec(q string, args ...any) (sql.Result, error)
	QueryRow(q string, args ...any) *sql.Row
}

func uniqueViolation(err error) bool {
	var pg *pgconn.PgError
	return errors.As(err, &pg) && pg.Code == "23505"
}

// openActionOf is the ticket's open action, or nil. lock takes it FOR UPDATE.
func openActionOf(x querier, ticket string, lock bool) *ticketAction {
	q := `SELECT id, ticket, kind, owner, coalesce(run,''), cycle_id, queue_id, opened
	      FROM ticket_actions WHERE ticket=? AND state='open'`
	if lock {
		q += ` FOR UPDATE`
	}
	a := &ticketAction{}
	if x.QueryRow(q, ticket).Scan(&a.id, &a.ticket, &a.kind, &a.owner, &a.run,
		&a.cycle, &a.queue, &a.opened) != nil {
		return nil
	}
	return a
}

// openAction inserts an open action. A unique violation means the ticket is
// held; in a transaction that also ends the transaction.
func openAction(x querier, a ticketAction) (int64, error) {
	var id int64
	err := x.QueryRow(`INSERT INTO ticket_actions
	        (ticket, kind, owner, run, cycle_id, queue_id, state, opened)
	        VALUES (?,?,?,?,?,?,'open',?) RETURNING id`,
		a.ticket, a.kind, a.owner, a.run, a.cycle, a.queue, wdNow()).Scan(&id)
	return id, err
}

func closeAction(x querier, id int64, state, why string) {
	_, _ = x.Exec(`UPDATE ticket_actions SET state=?, closed=?, why=?
	                         WHERE id=? AND state='open'`, state, wdNow(), why, id)
}

// actionSaid keeps "held by" lines to one per holder and asker: the keeper
// asks every quarter of an hour and the watchdog every tick.
var actionSaid sync.Map

func sayHeldOnce(asker, ticket string, holder *ticketAction) {
	if holder == nil {
		return
	}
	if _, said := actionSaid.LoadOrStore(fmt.Sprintf("%s|%s|%d", asker, ticket, holder.id), true); said {
		return
	}
	log.Printf("ammit: %s leaves %s alone: it is held by %s", asker, ticket, holder)
}

// queueUnderAction queues a resume of the ticket under a new resume action,
// in one transaction. 0 and the holder when the ticket is already held.
func queueUnderAction(ticket, owner, run, payload string) (int64, *ticketAction) {
	mu.Lock()
	defer mu.Unlock()
	tx, err := db.Begin()
	if err != nil {
		return 0, nil
	}
	id, err := openAction(tx, ticketAction{ticket: ticket, kind: actResume, owner: owner, run: run})
	if err != nil {
		_ = tx.Rollback()
		if uniqueViolation(err) {
			return 0, openActionOf(db, ticket, false)
		}
		log.Printf("ammit: could not open a resume action on %s: %v", ticket, err)
		return 0, nil
	}
	var q int64
	err = tx.QueryRow(`INSERT INTO queue (name, payload, requested) VALUES (?,?,?) RETURNING id`,
		ticket, payload, wdNow()).Scan(&q)
	if err == nil {
		_, err = tx.Exec(`UPDATE ticket_actions SET queue_id=? WHERE id=?`, q, id)
	}
	if err == nil {
		err = tx.Commit()
	}
	if err != nil {
		_ = tx.Rollback()
		log.Printf("ammit: could not queue the resume of %s: %v", ticket, err)
		return 0, nil
	}
	return q, nil
}

// openCycleAction opens the fix action of a cycle in the transaction that
// inserts the cycle. false and the holder when the ticket is held.
func openCycleAction(tx *Tx, ticket, run string, cycle int64) (*ticketAction, error) {
	_, err := openAction(tx, ticketAction{ticket: ticket, kind: actFix, owner: "watchdog", run: run,
		cycle: sql.NullInt64{Int64: cycle, Valid: true}})
	if err != nil && uniqueViolation(err) {
		return openActionOf(db, ticket, false), err
	}
	return nil, err
}

// holdCycle is the cycle's fix action: open already, or opened now for a
// cycle that has none - one started before this table, or one whose action a
// stop took over. nil and the holder when someone else has the ticket.
func holdCycle(c wdCycle, ticket string) (*ticketAction, *ticketAction) {
	mu.Lock()
	defer mu.Unlock()
	if a := openActionOf(db, ticket, false); a != nil {
		if a.kind == actFix && a.cycle.Valid && a.cycle.Int64 == c.id {
			return a, nil
		}
		return nil, a
	}
	if _, err := openAction(db, ticketAction{ticket: ticket, kind: actFix, owner: "watchdog",
		run: c.run, cycle: sql.NullInt64{Int64: c.id, Valid: true}}); err != nil {
		return nil, openActionOf(db, ticket, false)
	}
	log.Printf("ammit: watchdog cycle %d of %s holds %s", c.id, shortRun(c.root), ticket)
	return openActionOf(db, ticket, false), nil
}

// closeCycleAction closes the fix action of a cycle that ended.
func closeCycleAction(cycle int64, state string) {
	result := "done"
	if state == wdFailed {
		result = "failed"
	}
	mu.Lock()
	defer mu.Unlock()
	_, _ = db.Exec(`UPDATE ticket_actions SET state=?, closed=?, why=?
	                         WHERE kind='fix' AND cycle_id=? AND state='open'`,
		result, wdNow(), "watchdog cycle "+fmt.Sprint(cycle)+" ended "+state, cycle)
}

// pendingRow says whether a queue row is still to become a run: waiting, or
// started with no run tied to it yet.
func pendingRow(x querier, q sql.NullInt64) bool {
	if !q.Valid {
		return false
	}
	var n int
	_ = x.QueryRow(`SELECT count(*) FROM queue WHERE id=? AND coalesce(run,'') = ''
	                          AND state IN ('waiting','running')`, q.Int64).Scan(&n)
	return n > 0
}

// queueCycleResume queues the cycle's resume under its fix action.
func queueCycleResume(a *ticketAction, ticket, payload string) int64 {
	mu.Lock()
	defer mu.Unlock()
	tx, err := db.Begin()
	if err != nil {
		return 0
	}
	var q int64
	err = tx.QueryRow(`INSERT INTO queue (name, payload, requested) VALUES (?,?,?) RETURNING id`,
		ticket, payload, wdNow()).Scan(&q)
	if err == nil {
		var res sql.Result
		res, err = tx.Exec(`UPDATE ticket_actions SET queue_id=? WHERE id=? AND state='open'`, q, a.id)
		if n, _ := rowsOf(res); err == nil && n == 0 {
			err = errors.New("the cycle's action was closed under it")
		}
	}
	if err == nil {
		err = tx.Commit()
	}
	if err != nil {
		_ = tx.Rollback()
		log.Printf("ammit: could not queue the resume of %s: %v", ticket, err)
		return 0
	}
	return q
}

func rowsOf(res sql.Result) (int64, error) {
	if res == nil {
		return 0, errors.New("no result")
	}
	return res.RowsAffected()
}

// queueByRequest is POST /queue. A resume is queued under the table's
// precedence (see the top of this file); anything else as it always was. It
// answers with the row and a line on the action, "" when there is nothing to
// say.
func queueByRequest(name, payload string) (int64, string) {
	var p map[string]any
	_ = json.Unmarshal([]byte(payload), &p)
	if rerun, _ := p["rerun"].(string); rerun != "resume" {
		mu.Lock()
		defer mu.Unlock()
		var q int64
		_ = db.QueryRow(`INSERT INTO queue (name, payload, requested) VALUES (?,?,?) RETURNING id`,
			name, payload, wdNow()).Scan(&q)
		return q, ""
	}
	source, _ := p["source_run"].(string)
	for try := 0; try < 2; try++ {
		q, said, err := personResume(name, source, payload)
		if err == nil || !uniqueViolation(err) {
			if said != "" {
				log.Printf("ammit: queue row %d (%s): %s", q, name, said)
			}
			return q, said
		}
	}
	return 0, "the ticket's action changed twice under this request; not queued"
}

func personResume(name, source, payload string) (int64, string, error) {
	mu.Lock()
	defer mu.Unlock()
	tx, err := db.Begin()
	if err != nil {
		return 0, "", err
	}
	holder := openActionOf(tx, name, true)
	var q int64
	if err = tx.QueryRow(`INSERT INTO queue (name, payload, requested) VALUES (?,?,?) RETURNING id`,
		name, payload, wdNow()).Scan(&q); err != nil {
		_ = tx.Rollback()
		return 0, "", err
	}
	said := ""
	replaceWaiting := func() bool {
		if !holder.queue.Valid {
			return false
		}
		res, _ := tx.Exec(`UPDATE queue SET state='done', finished=? WHERE id=? AND state='waiting'`,
			wdNow(), holder.queue.Int64)
		n, _ := rowsOf(res)
		return n > 0
	}
	own := func() error {
		_, err := openAction(tx, ticketAction{ticket: name, kind: actResume, owner: "person", run: source,
			queue: sql.NullInt64{Int64: q, Valid: true}})
		return err
	}
	switch {
	case holder == nil:
		err = own()
	case holder.kind == actResume:
		if replaceWaiting() {
			closeAction(tx, holder.id, "done", fmt.Sprintf("replaced by a person's request (queue row %d)", q))
			said = fmt.Sprintf("replaces the waiting %s", holder)
			err = own()
		} else {
			said = fmt.Sprintf("queued beside %s, whose row is already starting", holder)
		}
	case holder.kind == actFix:
		// The cycle's own resume, or a person's taken before it, is replaced
		// while it waits; one that has become a run is the cycle's to follow
		// and stays its resume_queue.
		old := holder.queue
		replaced := false
		if pendingRow(tx, old) {
			if replaced = replaceWaiting(); !replaced {
				said = fmt.Sprintf("queued beside %s, whose resume is already starting", holder)
				break
			}
		}
		_, err = tx.Exec(`UPDATE ticket_actions SET queue_id=? WHERE id=?`, q, holder.id)
		if err == nil && replaced && holder.cycle.Valid {
			_, err = tx.Exec(`UPDATE watchdog_cycles SET resume_queue=?, updated=?
			                            WHERE id=? AND resume_queue=?`, q, wdNow(), holder.cycle.Int64, old.Int64)
		}
		said = fmt.Sprintf("taken as the resume of %s", holder)
	default: // a stop
		said = fmt.Sprintf("queued beside %s: the ticket's run is closing", holder)
	}
	if err == nil {
		err = tx.Commit()
	}
	if err != nil {
		_ = tx.Rollback()
		return 0, "", err
	}
	return q, said, nil
}

// openStop records a stop of a run as the ticket's action, taking over any
// open resume or fix. The caller does not hold mu.
func openStop(run, name, owner string) int64 {
	if run == "" {
		return 0
	}
	mu.Lock()
	defer mu.Unlock()
	var ticket string
	var finished sql.NullFloat64
	if db.QueryRow(`SELECT coalesce(name,''), finished FROM runs WHERE run=?`, run).
		Scan(&ticket, &finished) != nil || finished.Valid {
		return 0
	}
	if ticket == "" {
		ticket = name
	}
	if ticket == "" {
		return 0
	}
	for try := 0; try < 2; try++ {
		tx, err := db.Begin()
		if err != nil {
			return 0
		}
		holder := openActionOf(tx, ticket, true)
		if holder != nil && holder.kind == actStop {
			_ = tx.Rollback()
			if holder.run != run {
				sayHeldOnce("the stop of "+shortRun(run), ticket, holder)
			}
			return 0
		}
		if holder != nil {
			why := fmt.Sprintf("taken over by a stop of run %s (%s)", shortRun(run), owner)
			if holder.kind == actResume && holder.queue.Valid {
				_, _ = tx.Exec(`UPDATE queue SET state='done', finished=? WHERE id=? AND state='waiting'`,
					wdNow(), holder.queue.Int64)
			}
			closeAction(tx, holder.id, "done", why)
			log.Printf("ammit: %s on %s %s", holder, ticket, why)
		}
		id, err := openAction(tx, ticketAction{ticket: ticket, kind: actStop, owner: owner, run: run})
		if err == nil {
			err = tx.Commit()
		}
		if err == nil {
			return id
		}
		_ = tx.Rollback()
		if !uniqueViolation(err) {
			log.Printf("ammit: could not record the stop of %s: %v", run, err)
			return 0
		}
	}
	return 0
}

// stopNotSent closes a stop whose command failed: nothing reached the run,
// so it is not closing, and ammit must not close its row for ignoring a stop
// it never got. The caller does not hold mu.
func stopNotSent(id int64, said string) {
	if id == 0 {
		return
	}
	mu.Lock()
	defer mu.Unlock()
	closeAction(db, id, "failed", "the stop command failed: "+said)
}

// closeStopsOf closes the stop of a run whose row just finished. The caller
// holds mu.
func closeStopsOf(run string, at float64) {
	_, _ = db.Exec(`UPDATE ticket_actions SET state='done', closed=?, why='the run ended'
	                         WHERE kind='stop' AND run=? AND state='open'`, at, run)
}

// closeResumesStarted closes the resume actions whose queue row has just been
// tied to the run it became. The caller holds mu.
func closeResumesStarted(run string, at float64) {
	_, _ = db.Exec(`UPDATE ticket_actions a SET state='done', closed=?,
	                           why='queue row ' || q.id || ' became run ' || q.run
	                         FROM queue q WHERE a.state='open' AND a.kind='resume'
	                           AND q.id = a.queue_id AND q.run = ?`, at, run)
}

// sweepActions closes, on the tick, every open action whose queue row, cycle
// or run says it is over - what a process that died between the two left
// open - and closes the row of a run that did not acknowledge its stop
// within timeouts.run_close.
func sweepActions(conf Config) {
	now := wdNow()
	moving := `('` + strings.Join(wdMoving, "','") + `')`
	closes := []string{
		// A resume: its row became a run, or was closed without one.
		`UPDATE ticket_actions a SET state='done', closed=?1,
		   why='queue row ' || q.id || ' became run ' || q.run
		 FROM queue q WHERE a.state='open' AND a.kind='resume' AND q.id = a.queue_id
		   AND coalesce(q.run,'') <> '' RETURNING a.ticket, a.kind, a.why`,
		`UPDATE ticket_actions a SET state='failed', closed=?1,
		   why='queue row ' || q.id || ' was closed without becoming a run (refused, withdrawn or answered)'
		 FROM queue q WHERE a.state='open' AND a.kind='resume' AND q.id = a.queue_id
		   AND q.state = 'done' AND coalesce(q.run,'') = '' RETURNING a.ticket, a.kind, a.why`,
		`UPDATE ticket_actions a SET state='failed', closed=?1, why='no queue row stands behind it'
		 WHERE a.state='open' AND a.kind='resume' AND a.opened < ?1 - 60
		   AND NOT EXISTS (SELECT 1 FROM queue q WHERE q.id = a.queue_id)
		 RETURNING a.ticket, a.kind, a.why`,
		// A fix: its cycle is no longer moving, or is gone.
		`UPDATE ticket_actions a SET state = CASE WHEN c.state = 'failed' THEN 'failed' ELSE 'done' END,
		   closed=?1, why='watchdog cycle ' || c.id || ' is ' || c.state
		 FROM watchdog_cycles c WHERE a.state='open' AND a.kind='fix' AND c.id = a.cycle_id
		   AND c.state NOT IN ` + moving + ` RETURNING a.ticket, a.kind, a.why`,
		// A cycle left in 'resumed' after its resumed run finished is not
		// moving: cycle 477 sat so from 10:52 on 2026-11-08 and its action
		// held APF-3313 against every resume for the rest of the day.
		`UPDATE ticket_actions a SET state='done', closed=?1,
		   why='watchdog cycle ' || c.id || ' resumed ' || c.resumed_run || ', which has finished'
		 FROM watchdog_cycles c, runs r
		 WHERE a.state='open' AND a.kind='fix' AND c.id = a.cycle_id
		   AND c.state = '` + wdResumed + `' AND r.run = c.resumed_run AND r.finished IS NOT NULL
		 RETURNING a.ticket, a.kind, a.why`,
		`UPDATE ticket_actions a SET state='failed', closed=?1, why='its watchdog cycle is gone'
		 WHERE a.state='open' AND a.kind='fix'
		   AND NOT EXISTS (SELECT 1 FROM watchdog_cycles c WHERE c.id = a.cycle_id)
		 RETURNING a.ticket, a.kind, a.why`,
		// A stop: its run's row is finished, or there is no such run.
		`UPDATE ticket_actions a SET state='done', closed=?1, why='the run ended'
		 FROM runs r WHERE a.state='open' AND a.kind='stop' AND r.run = a.run
		   AND r.finished IS NOT NULL RETURNING a.ticket, a.kind, a.why`,
		`UPDATE ticket_actions a SET state='failed', closed=?1, why='no such run'
		 WHERE a.state='open' AND a.kind='stop'
		   AND NOT EXISTS (SELECT 1 FROM runs r WHERE r.run = a.run)
		 RETURNING a.ticket, a.kind, a.why`,
	}
	type stale struct {
		id                 int64
		ticket, run, owner string
		opened             float64
	}
	var stops []stale
	mu.Lock()
	for _, q := range closes {
		rows, err := db.Query(q, now)
		if err != nil {
			log.Printf("ammit: sweeping ticket actions: %v", err)
			continue
		}
		for rows.Next() {
			var ticket, kind, why string
			if rows.Scan(&ticket, &kind, &why) == nil {
				log.Printf("ammit: %s action on %s closed: %s", kind, ticket, why)
			}
		}
		_ = rows.Err() // a cut-off read closes the rest next tick
		rows.Close()
	}
	if rows, err := db.Query(`SELECT id, ticket, run, owner, opened FROM ticket_actions
	                                     WHERE state='open' AND kind='stop'`); err == nil {
		for rows.Next() {
			var s stale
			if rows.Scan(&s.id, &s.ticket, &s.run, &s.owner, &s.opened) == nil {
				stops = append(stops, s)
			}
		}
		_ = rows.Err() // a cut-off read is the shorter answer it always was
		rows.Close()
	}
	mu.Unlock()
	limit, ok := conf.num("timeouts", "run_close")
	if !ok {
		limit = 300
	}
	if limit <= 0 {
		return
	}
	// Measured awake, as every age here: a stop ordered just before the host
	// slept is not a stop the run ignored.
	up := nowWall() - upSince()
	for _, s := range stops {
		waited := now - s.opened
		if up < waited {
			waited = up
		}
		if waited <= limit {
			continue
		}
		why := fmt.Sprintf("force-closed by ammit: the stop ordered by %s at %s was not "+
			"acknowledged within timeouts.run_close (%.0fs)", s.owner,
			time.Unix(int64(s.opened), 0).UTC().Format("15:04:05 UTC"), limit)
		mu.Lock()
		closeAction(db, s.id, "failed", why)
		mu.Unlock()
		finish(s.run, "BLOCKED", why)
		judge("run", s.run, s.ticket, "timeouts.run_close", limit, waited, "closed", why)
	}
}
